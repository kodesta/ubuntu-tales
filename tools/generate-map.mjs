#!/usr/bin/env node
/**
 * Generates the world/Africa SVG geometry used by the `/explore` map.
 *
 * Source: Natural Earth 1:110m country boundaries shipped with `world-atlas` (public domain).
 * Projection: equirectangular (lon/lat → 1000×500 viewBox). The output is a committed TS module so
 * the runtime needs no mapping dependency and the map chunk stays small.
 *
 * Usage: node tools/generate-map.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const topo = require('world-atlas/countries-110m.json');
const { feature } = require('topojson-client');

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'apps/web/src/features/explore/world-geometry.ts');

const WIDTH = 1000;
const HEIGHT = 500;

/** ISO 3166-1 numeric codes for African countries (world-atlas uses numeric ids). */
const AFRICA_IDS = new Set([
  '12', '24', '204', '72', '854', '108', '132', '120', '140', '148', '174', '178', '180',
  '384', '262', '818', '226', '232', '748', '231', '266', '270', '288', '324', '624', '404',
  '426', '430', '434', '450', '454', '466', '478', '480', '504', '508', '516', '562', '566',
  '646', '678', '686', '690', '694', '706', '710', '728', '729', '834', '768', '788', '800',
  '894', '716', '732',
]);

export function project(lat, lng) {
  const x = ((lng + 180) / 360) * WIDTH;
  const y = ((90 - lat) / 180) * HEIGHT;
  return [Math.round(x * 10) / 10, Math.round(y * 10) / 10];
}

function ringToPath(ring) {
  return ring
    .map(([lng, lat], index) => {
      const [x, y] = project(lat, lng);
      return `${index === 0 ? 'M' : 'L'}${x},${y}`;
    })
    .join(' ')
    .concat(' Z');
}

function geometryToPath(geometry) {
  if (!geometry) return '';
  if (geometry.type === 'Polygon') {
    return geometry.coordinates.map(ringToPath).join(' ');
  }
  if (geometry.type === 'MultiPolygon') {
    return geometry.coordinates.flatMap((polygon) => polygon.map(ringToPath)).join(' ');
  }
  return '';
}

const collection = feature(topo, topo.objects.countries);
let worldPath = '';
let africaPath = '';

for (const country of collection.features) {
  const id = String(country.id ?? '').replace(/^0+/, '');
  const d = geometryToPath(country.geometry);
  if (!d) continue;
  worldPath += d;
  if (AFRICA_IDS.has(id)) africaPath += d;
}

const module = `/* eslint-disable */
// AUTO-GENERATED by tools/generate-map.mjs — do not edit by hand.
// Natural Earth 1:110m country boundaries (public domain, via world-atlas), equirectangular
// projection into a ${WIDTH}×${HEIGHT} viewBox.

export const MAP_WIDTH = ${WIDTH};
export const MAP_HEIGHT = ${HEIGHT};

/** Whole world, muted landmass. */
export const WORLD_PATH =
  '${worldPath}';

/** African continent, drawn on top for emphasis. */
export const AFRICA_PATH =
  '${africaPath}';

/** Approximate Africa viewBox (lon -25..57, lat 37..-35) with padding. */
export const AFRICA_VIEWBOX = '400 120 300 250';

export const WORLD_VIEWBOX = '0 0 ${WIDTH} ${HEIGHT}';

export function projectToMap(lat: number, lng: number): { x: number; y: number } {
  return {
    x: Math.round((((lng + 180) / 360) * ${WIDTH}) * 10) / 10,
    y: Math.round((((90 - lat) / 180) * ${HEIGHT}) * 10) / 10,
  };
}
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, module);
console.log(`Wrote ${path.relative(ROOT, OUT)}`);
console.log(`  world path: ${(worldPath.length / 1024).toFixed(1)} KB`);
console.log(`  africa path: ${(africaPath.length / 1024).toFixed(1)} KB`);
